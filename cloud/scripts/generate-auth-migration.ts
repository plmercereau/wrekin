// Generates migrations/0001_auth.sql from the Better Auth configuration in src/auth.ts.
//
// This calls the schema generator Better Auth ships (`getMigrations`), the one the
// `@better-auth/cli generate` command wraps, from the very version of the library the
// Worker runs. The published CLI lags the library and omitted three unique indexes
// when it was tried. The configuration is bound to an in-memory bun:sqlite database
// only so the generator can introspect an (empty) SQLite schema; the Worker builds the
// same configuration over D1.
//
// Run with `bun run db:generate`. This file lives outside tsconfig's `include`
// because `bun:sqlite` has no type declarations in a Workers project.
import { Database } from "bun:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { buildAuth } from "../src/auth";

const auth = buildAuth({
  baseURL: "https://wrekin.platyplus.io",
  secret: "schema-generation-only-not-a-secret",
  database: new Database(":memory:"),
  github: { clientId: "unused", clientSecret: "unused" },
  google: { clientId: "unused", clientSecret: "unused" },
});

const { compileMigrations } = await getMigrations(auth.options);
const sql = (await compileMigrations()).trim();

const header = [
  "-- Better Auth schema for src/auth.ts: user, session, account, verification, jwks,",
  "-- deviceCode and the OAuth provider tables. Generated by",
  "-- scripts/generate-auth-migration.ts; do not edit, run `bun run db:generate`.",
  "",
].join("\n");

await Bun.write(new URL("../migrations/0001_auth.sql", import.meta.url), `${header}${sql}\n`);
console.log("wrote migrations/0001_auth.sql");
